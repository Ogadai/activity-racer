import type { RuntimeConfig } from '@activity-racer/shared';

let cachedConfig: RuntimeConfig | null = null;

export async function loadRuntimeConfig(): Promise<RuntimeConfig> {
  if (cachedConfig) {
    return cachedConfig;
  }

  // Local dev override via Vite env vars
  const envApiUrl = import.meta.env.VITE_API_URL as string | undefined;
  if (envApiUrl) {
    cachedConfig = {
      apiUrl: envApiUrl.replace(/\/+$/, ''),
      region: (import.meta.env.VITE_AWS_REGION as string | undefined) ?? 'eu-north-1',
      userPoolId: import.meta.env.VITE_USER_POOL_ID as string | undefined,
      userPoolClientId: import.meta.env.VITE_USER_POOL_CLIENT_ID as string | undefined,
    };
    return cachedConfig;
  }

  // Deployed build reads runtime /config.json generated by AWS CDK
  const response = await fetch('/config.json', { cache: 'no-store' });
  if (!response.ok) {
    throw new Error(`Failed to load /config.json (HTTP ${response.status})`);
  }

  const data = (await response.json()) as RuntimeConfig;
  cachedConfig = {
    ...data,
    apiUrl: data.apiUrl.replace(/\/+$/, ''),
  };
  return cachedConfig;
}
